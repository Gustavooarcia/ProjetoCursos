alter table public.alunos enable row level security;
alter table public.cursos enable row level security;
alter table public.matriculas enable row level security;

drop policy if exists "laboratorio_anon_select_alunos" on public.alunos;
drop policy if exists "laboratorio_anon_insert_alunos" on public.alunos;
drop policy if exists "laboratorio_anon_update_alunos" on public.alunos;
drop policy if exists "laboratorio_anon_delete_alunos" on public.alunos;

create policy "laboratorio_anon_select_alunos" on public.alunos for select to anon, authenticated using (true);
create policy "laboratorio_anon_insert_alunos" on public.alunos for insert to anon, authenticated with check (true);
create policy "laboratorio_anon_update_alunos" on public.alunos for update to anon, authenticated using (true) with check (true);
create policy "laboratorio_anon_delete_alunos" on public.alunos for delete to anon, authenticated using (true);

