

create table if not exists public.alunos (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(trim(nome)) >= 3),
  email text not null unique check (position('@' in email) > 1),
  telefone text,
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

create table if not exists public.cursos (
  id bigint generated by default as identity primary key,
  nome text not null,
  descricao text,
  carga_horaria integer not null check (carga_horaria > 0),
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

create table if not exists public.matriculas (
  id bigint generated by default as identity primary key,
  aluno_id bigint not null references public.alunos(id) on delete cascade,
  curso_id bigint not null references public.cursos(id) on delete cascade,
  status text not null default 'ativa' check (status in ('ativa', 'concluida', 'cancelada')),
  data_matricula date not null default current_date,
  unique (aluno_id, curso_id)
);

